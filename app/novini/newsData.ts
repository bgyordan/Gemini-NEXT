export function getAllNews(): NewsPost[] {
  return NEWS_POSTS;
}

export function getLatestNews(count = 3): NewsPost[] {
  return NEWS_POSTS.slice(0, count);
}

export function getFeaturedNews(): NewsPost | undefined {
  return NEWS_POSTS.find((p) => p.featured) || NEWS_POSTS[0];
}

export function getNewsBySlug(slug: string): NewsPost | undefined {
  return NEWS_POSTS.find((p) => p.slug === slug);
}

export function getRelatedNews(currentSlug: string, count = 2): NewsPost[] {
  return NEWS_POSTS.filter((p) => p.slug !== currentSlug).slice(0, count);
}
